#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/common.sh"

mkdir -p "${PLATFORM_BOOTSTRAP_STATE_DIR}"

INSTANCE_CONFIG="${PLATFORM_BOOTSTRAP_STATE_DIR}/instance.env"
TMP_CONFIG="${INSTANCE_CONFIG}.tmp"

cat > "${TMP_CONFIG}" <<EOF
PLATFORM_BOOTSTRAP_NAME=${PLATFORM_BOOTSTRAP_NAME}
KIND_CLUSTER=${KIND_CLUSTER}
KIND_HTTP_PORT=${KIND_HTTP_PORT}
KIND_HTTPS_PORT=${KIND_HTTPS_PORT}
REGISTRY_NAME=${REGISTRY_NAME}
REGISTRY_HOST=${REGISTRY_HOST}
REGISTRY_PORT=${REGISTRY_PORT}
EOF

mv "${TMP_CONFIG}" "${INSTANCE_CONFIG}"

echo "==> Configuration de l'instance enregistrée"
echo "    ${INSTANCE_CONFIG}"
